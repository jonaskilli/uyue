/**
 * AI 生图预设库：题材模板 + 画风风格提示词。
 *
 * 数据移植自 yuedu666 分支的 `model/AiImageStylePresets.kt`，但只取其中「题材」与「画风」
 * 两类，按当前项目的用法重新组织：
 *  - 参考版的「书籍画像」在本项目落为 [Genre] 的题材模板；
 *  - 参考版的「画风预设 stylePrompt」在本项目落为 [ArtStyle.stylePrompt]。
 *  - 参考版的「画面版式 / 时代约束 / mood 关键词」本项目暂不引入，保持简单。
 *
 * 【占位符约束（重要）】
 * 当前项目 [AiImageGenerator.buildPrompt] 只会替换 `{text}`、`{book}`、`{style}` 三个占位符，
 * 替换不到的占位符会以**字面量**形式发给模型。所以这里的模板只允许使用这三个，
 * 绝不能出现参考版里的 {mood}/{scene}/{sceneType}/{elements}/{characters}，
 * 否则会把 "{scene}" 这种字符串直接发给 API。
 */
