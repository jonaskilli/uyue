# 这里的取舍：只放行**事物名词**（雷、剑、门、碗、马…），
# 一律禁掉**动作 / 多义字**（打、行、开、倒、包、压、走、动、声、气）——
# 后者正是误伤的来源。
SAFE_SINGLE_ANCHORS = set(
    "雷雨雪风霜雾冰雹火水海江河湖波涛浪"
    "剑刀枪弓箭盾甲炮弹刃鞘"
    "马牛羊猪鸡鸭鹅猫狗狼虎狮龙蛇鸟虫鱼蜂蝉"
    "门窗锁钥铃钟鼓锣琴笛箫弦"
    "碗杯盘壶瓶罐桶锅勺筷"
    "书纸笔墨印章"
    "灯烛香蜡"
    "心血泪汗手脚掌"
    "链绳铁铜银金石沙土木竹草花叶树"
    "山路桥车船机电"
)


def merge_additions():
    """把 [GROUP_ADDITIONS] 并进 [GROUPS]，组不存在就新建。"""
    for group, words in GROUP_ADDITIONS.items():
        target = GROUPS.setdefault(group, [])
        for w in words:
            if w not in target:
                target.append(w)


merge_additions()


def build_anchor_map():
    """
    词 -> 所属概念组（一个词可能属于多个组）。

    **只用 2 字及以上的词当锚点，1 字词只作输出、不参与匹配。**
    这是踩过坑的结论（见 `docs/ai_effect_category/README.md` 第 8 节）：
    单字锚点误伤极其严重——

        家具自行挪动  含"行" -> 脚步    单次打喷嚏  含"打" -> 打斗
        包饺子        含"包" -> 箱包    倒麦片入碗  含"倒" -> 跌倒
        药力化开      含"开" -> 开合    压低的笑声  含"压" -> 威压

    宁可少覆盖一些，也不能成片配错：配错的关键词会污染候选池，
    把真正相关的音效挤掉，比不配更糟。
    """
    anchors = {}
    for group, words in GROUPS.items():
        for w in words:
            if len(w) < MIN_ANCHOR_LEN and w not in SAFE_SINGLE_ANCHORS:
                continue
            anchors.setdefault(w, []).append(group)
    # 长词优先命中，避免短词抢先
    return dict(sorted(anchors.items(), key=lambda kv: -len(kv[0])))


ANCHORS = build_anchor_map()


def strip_attr(name):
    core = TRAILING_NOISE.sub('', name)
    for suf in ATTR_SUFFIXES:
        if len(core) > len(suf) and core.endswith(suf):
            core = core[: -len(suf)]
            break
    return core


def keywords_of(name, max_kw=MAX_KEYWORDS):
    """
    给一个音效名产出关键词：只保留 **不在名字里** 的 2 字词。

    组内**按词表原序**取，不要按「与命中锚点的字面重合度」重排。
    试过重排，结果是灾难性的：同义词本来就不共享字面
    （"脚步" 的同义词是 "走路"，一个字都不重合），
    按重合度排序等于把真正的同义词排到最后、被 6 个名额切掉，
    "走路" 的命中量直接从 137 掉到 49。
    要让"打响指"拿到"手指"而不是"揉搓"，正确做法是把组拆细（见 [GROUPS] 的手部/腿部/躯干/头面）。
    """
    hit_groups = []
    seen_groups = set()
    for word, groups in ANCHORS.items():
        if word in name:
            for g in groups:
                if g not in seen_groups:
                    seen_groups.add(g)
                    hit_groups.append(g)
    out = []
    seen_kw = set()
    for g in hit_groups:
        for w in GROUPS[g]:
            # 只输出 2 字：AI 关键字被截断到 1~2 字，2 字对齐度最高
            if len(w) != 2:
                continue
            # 名字子串 = 本来就命中，加了纯属浪费体积
            if w in name:
                continue
            # AI 给不出的词（书面语 / 术语 / 抽象词）：加了只会污染候选池
            if w in NOT_TEXTUAL:
                continue
            if w in seen_kw:
                continue
            seen_kw.add(w)
            out.append(w)
            if len(out) >= max_kw:
                return out
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-i', '--input', default=DEFAULT_INDEX)
    ap.add_argument('-o', '--output', default=None)
    ap.add_argument('--max', type=int, default=MAX_KEYWORDS)
    ap.add_argument('--report', action='store_true', help='打印未命中概念的样例')
    args = ap.parse_args()

    with open(args.input, encoding='utf-8') as f:
        data = json.load(f)

    total = 0
    with_kw = 0
    kw_count = Counter()
    miss_examples = []
    result = {}

    for cat, subs in data.items():
        out_subs = {}
        for sub, arr in subs.items():
            out_arr = []
            for name in arr:
                total += 1
                kws = keywords_of(name, args.max)
                if kws:
                    with_kw += 1
                    kw_count[len(kws)] += 1
                    out_arr.append(name + '|' + '|'.join(kws))
                else:
                    out_arr.append(name)
                    if len(miss_examples) < 60:
                        miss_examples.append(name)
            out_subs[sub] = out_arr
        result[cat] = out_subs

    print('音效总数      : %d' % total)
    print('拿到关键词    : %d (%.1f%%)' % (with_kw, 100.0 * with_kw / max(total, 1)))
    print('无关键词      : %d' % (total - with_kw))
    print('每名关键词数  : %s' % dict(sorted(kw_count.items())))
    if args.report:
        print('\n未命中概念的名字样例：')
        print('、'.join(miss_examples))

    if args.output:
        with open(args.output, 'w', encoding='utf-8') as f:
            json.dump(result, f, ensure_ascii=False, indent=2)
        print('\n已写出: %s (%d 字节)' % (args.output, os.path.getsize(args.output)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
